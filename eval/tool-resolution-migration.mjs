#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SEP = '\n\n--- CONTEXT ARTIFACT ---\n\n';

const readText = relativePath => readFile(path.join(root, relativePath), 'utf8');
const readJson = async relativePath => JSON.parse(await readText(relativePath));
const metrics = value => {
  const bytes = Buffer.byteLength(value, 'utf8');
  return { utf8_bytes: bytes, rough_tokens: Math.ceil(bytes / 4) };
};
const delta = (current, reference) => ({
  utf8_bytes: current.utf8_bytes - reference.utf8_bytes,
  rough_tokens: current.rough_tokens - reference.rough_tokens,
  percent: Number((((current.utf8_bytes - reference.utf8_bytes) / reference.utf8_bytes) * 100).toFixed(1))
});

export async function buildToolResolutionMigrationReport() {
  const [agents, bootstrap, tools, skill, bundleText, phase9] = await Promise.all([
    readText('AGENTS.md'),
    readText('content/site-orientation.json'),
    readText('content/orientation/tools.json'),
    readText('.agents/skills/tool-discovery-and-safe-execution/SKILL.md'),
    readText('dist/data/agent-context/tool-resolution.json'),
    readJson('eval/results/system-map-context-experiment.json')
  ]);

  const bundle = JSON.parse(bundleText);
  const baseline = phase9.fixtures.find(item => item.route_id === 'tool-resolution')?.control;
  if (!baseline) throw new Error('Phase 9 tool-resolution baseline is unavailable.');

  const preferred = metrics([agents, bundleText, skill].join(SEP));
  const fallback = metrics([agents, bootstrap, tools, skill].join(SEP));
  const phase9Baseline = { utf8_bytes: baseline.utf8_bytes, rough_tokens: baseline.rough_tokens };

  return {
    schema_version: '1.0',
    migration: 'tool-resolution-graph-backed-context',
    estimator: 'utf8-byte-count-divided-by-four',
    estimator_formula: 'ceil(UTF-8 bytes / 4)',
    canonical_route_records_changed: false,
    preferred_path: {
      artifacts: [
        'AGENTS.md',
        'dist/data/agent-context/tool-resolution.json',
        '.agents/skills/tool-discovery-and-safe-execution/SKILL.md'
      ],
      ...preferred
    },
    canonical_fallback: {
      artifacts: [
        'AGENTS.md',
        'content/site-orientation.json',
        'content/orientation/tools.json',
        '.agents/skills/tool-discovery-and-safe-execution/SKILL.md'
      ],
      ...fallback
    },
    phase9_control_baseline: phase9Baseline,
    deltas: {
      preferred_vs_current_fallback: delta(preferred, fallback),
      preferred_vs_phase9_control: delta(preferred, phase9Baseline)
    },
    bundle: {
      utf8_bytes: Buffer.byteLength(bundleText, 'utf8'),
      rough_tokens: Math.ceil(Buffer.byteLength(bundleText, 'utf8') / 4),
      graph_nodes: bundle.graph_fragment.nodes.length,
      graph_edges: bundle.graph_fragment.edges.length,
      provenance_entries: Object.keys(bundle.graph_fragment.provenance).length,
      space_entries: bundle.space_index.length,
      route_id: bundle.route_id,
      primary_space: bundle.primary_space,
      package_path: bundle.package_path,
      mutation_boundary: bundle.exceptions.mutation_boundary,
      change_mode: bundle.contract.change_mode,
      reconciliation: bundle.contract.reconciliation,
      live_state_embedded: false
    },
    interpretation: [
      'The preferred-path metric retains the full root AGENTS.md because the repository harness may activate it automatically.',
      'The Tool bundle deliberately omits bootstrap, space, and route-group graph traversal already resolved by direct dispatch; its one-entry space_index preserves Tools ownership.',
      'The bundle keeps route→Skill, Skill contract, live-runtime exclusion, validation, and reconciliation provenance.',
      'Current availability, credentials, permission, workspace, target, approval, and execution results remain external and are never serialized into the bundle.',
      'Rough-token estimates are static UTF-8/4 approximations, not observed model or subscription usage.'
    ]
  };
}

function markdown(report) {
  return [
    '# Tool-resolution graph-backed context migration',
    '',
    'Generated by eval/tool-resolution-migration.mjs.',
    '',
    '| Condition | UTF-8 bytes | Rough tokens |',
    '| --- | ---: | ---: |',
    '| Phase 9 pre-migration control | ' + report.phase9_control_baseline.utf8_bytes + ' | ' + report.phase9_control_baseline.rough_tokens + ' |',
    '| Current canonical fallback | ' + report.canonical_fallback.utf8_bytes + ' | ' + report.canonical_fallback.rough_tokens + ' |',
    '| Migrated preferred path | ' + report.preferred_path.utf8_bytes + ' | ' + report.preferred_path.rough_tokens + ' |',
    '',
    'Preferred vs current fallback: **' + report.deltas.preferred_vs_current_fallback.percent + '%** (' + report.deltas.preferred_vs_current_fallback.utf8_bytes + ' bytes / ' + report.deltas.preferred_vs_current_fallback.rough_tokens + ' rough tokens).',
    '',
    'Preferred vs Phase 9 pre-migration control: **' + report.deltas.preferred_vs_phase9_control.percent + '%** (' + report.deltas.preferred_vs_phase9_control.utf8_bytes + ' bytes / ' + report.deltas.preferred_vs_phase9_control.rough_tokens + ' rough tokens).',
    '',
    '## Bundle',
    '',
    '- Route: tool-resolution.',
    '- Graph fragment: ' + report.bundle.graph_nodes + ' nodes / ' + report.bundle.graph_edges + ' edges.',
    '- Provenance entries: ' + report.bundle.provenance_entries + '.',
    '- Space entries: ' + report.bundle.space_entries + '.',
    '- Mutation boundary: ' + report.bundle.mutation_boundary + '.',
    '- Change mode: ' + report.bundle.change_mode + '.',
    '- Reconciliation: ' + report.bundle.reconciliation + '.',
    '- Live state embedded: no.',
    '',
    '## Interpretation',
    '',
    ...report.interpretation.map(item => '- ' + item),
    '',
    'Canonical Tool routing and live runtime state remain authoritative in their native sources. The generated bundle is only a preferred route context.'
  ].join('\n') + '\n';
}

export async function expectedToolResolutionMigrationOutputs() {
  const report = await buildToolResolutionMigrationReport();
  return new Map([
    ['eval/results/tool-resolution-migration.json', JSON.stringify(report, null, 2) + '\n'],
    ['eval/tool-resolution-migration.md', markdown(report)]
  ]);
}

export async function writeToolResolutionMigrationOutputs({ check = false } = {}) {
  const outputs = await expectedToolResolutionMigrationOutputs();
  const stale = [];
  for (const [relativePath, content] of outputs) {
    const filePath = path.join(root, relativePath);
    if (check) {
      let current = null;
      try { current = await readFile(filePath, 'utf8'); } catch {}
      if (current !== content) stale.push(relativePath);
    } else {
      await mkdir(path.dirname(filePath), { recursive: true });
      await writeFile(filePath, content, 'utf8');
    }
  }
  if (stale.length) throw new Error('Tool-resolution migration report is stale: ' + stale.join(', '));
  return outputs;
}

const entry = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (entry) {
  const outputs = await writeToolResolutionMigrationOutputs({ check: process.argv.includes('--check') });
  const report = JSON.parse(outputs.get('eval/results/tool-resolution-migration.json'));
  console.log('Tool-resolution migrated preferred path: ' + report.preferred_path.utf8_bytes + ' bytes; ' + report.deltas.preferred_vs_current_fallback.percent + '% vs current fallback.');
}
