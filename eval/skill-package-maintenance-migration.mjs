#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SEP = '\n\n--- CONTEXT ARTIFACT ---\n\n';

const readText = relativePath => readFile(path.join(root, relativePath), 'utf8');

function metrics(value) {
  const bytes = Buffer.byteLength(value, 'utf8');
  return { utf8_bytes: bytes, rough_tokens: Math.ceil(bytes / 4) };
}

function delta(current, reference) {
  return {
    utf8_bytes: current.utf8_bytes - reference.utf8_bytes,
    rough_tokens: current.rough_tokens - reference.rough_tokens,
    percent: Number((((current.utf8_bytes - reference.utf8_bytes) / reference.utf8_bytes) * 100).toFixed(1))
  };
}

export async function buildSkillPackageMaintenanceMigrationReport() {
  const [agents, bootstrap, skills, skill, bundleText] = await Promise.all([
    readText('AGENTS.md'),
    readText('content/site-orientation.json'),
    readText('content/orientation/skills.json'),
    readText('.agents/skills/pl-skill-creator/SKILL.md'),
    readText('dist/data/agent-context/skill-package-maintenance.json')
  ]);

  const bundle = JSON.parse(bundleText);
  const preferred = metrics([agents, bundleText, skill].join(SEP));
  const fallback = metrics([agents, bootstrap, skills, skill].join(SEP));

  return {
    schema_version: '1.0',
    migration: 'skill-package-maintenance-graph-backed-context',
    estimator: 'utf8-byte-count-divided-by-four',
    estimator_formula: 'ceil(UTF-8 bytes / 4)',
    canonical_route_records_changed: true,
    preferred_path: {
      artifacts: [
        'AGENTS.md',
        'dist/data/agent-context/skill-package-maintenance.json',
        '.agents/skills/pl-skill-creator/SKILL.md'
      ],
      ...preferred
    },
    canonical_fallback: {
      artifacts: [
        'AGENTS.md',
        'content/site-orientation.json',
        'content/orientation/skills.json',
        '.agents/skills/pl-skill-creator/SKILL.md'
      ],
      ...fallback
    },
    deltas: {
      preferred_vs_current_fallback: delta(preferred, fallback)
    },
    exit_gate: {
      minimum_context_reduction_percent: 10,
      context_gate_pass: delta(preferred, fallback).percent <= -10,
      route_selection_file_reads: { control: 2, preferred: 1 },
      completion_file_reads: { control: 3, preferred: 2 },
      static_artifacts_loaded: { control: 4, preferred: 3 },
      artifact_count_increase: false
    },
    bundle: {
      utf8_bytes: Buffer.byteLength(bundleText, 'utf8'),
      rough_tokens: Math.ceil(Buffer.byteLength(bundleText, 'utf8') / 4),
      graph_nodes: bundle.graph_fragment.nodes.length,
      graph_edges: bundle.graph_fragment.edges.length,
      provenance_entries: Object.keys(bundle.graph_fragment.provenance).length,
      space_entries: bundle.space_index.length,
      route_id: bundle.route_id,
      primary_space: bundle.primary_space,
      package_path: bundle.package_path,
      mutation_boundary: bundle.exceptions.mutation_boundary,
      change_mode: bundle.contract.change_mode,
      reconciliation: bundle.contract.reconciliation,
      live_state_embedded: false
    },
    interpretation: [
      'The preferred-path metric retains the full root AGENTS.md because the repository harness may activate it automatically.',
      'The Skill-package bundle uses the ordinary one-space v0.1 graph shape; no route-specific schema or generator special case is required.',
      'Approved scope, existing-package content, placement decisions, mutation authorization, runtime availability, permissions, and current repository state remain external and are never serialized into the bundle.',
      'The preferred path removes one route-selection read, one completion read, and one static artifact while preserving the canonical Skills fallback.',
      'Rough-token estimates are static UTF-8/4 approximations, not observed model or subscription usage.'
    ]
  };
}

function markdown(report) {
  return [
    '# Skill-package-maintenance graph-backed context migration',
    '',
    'Generated by eval/skill-package-maintenance-migration.mjs.',
    '',
    '| Condition | UTF-8 bytes | Rough tokens |',
    '| --- | ---: | ---: |',
    '| Current canonical fallback | ' + report.canonical_fallback.utf8_bytes + ' | ' + report.canonical_fallback.rough_tokens + ' |',
    '| Migrated preferred path | ' + report.preferred_path.utf8_bytes + ' | ' + report.preferred_path.rough_tokens + ' |',
    '',
    'Preferred vs current fallback: **' + report.deltas.preferred_vs_current_fallback.percent + '%** (' + report.deltas.preferred_vs_current_fallback.utf8_bytes + ' bytes / ' + report.deltas.preferred_vs_current_fallback.rough_tokens + ' rough tokens).',
    '',
    '## Exit gate',
    '',
    '- Required base reduction: at least ' + report.exit_gate.minimum_context_reduction_percent + '%.',
    '- Context gate: ' + (report.exit_gate.context_gate_pass ? 'PASS' : 'FAIL') + '.',
    '- Route-selection reads: ' + report.exit_gate.route_selection_file_reads.control + '→' + report.exit_gate.route_selection_file_reads.preferred + '.',
    '- Completion reads: ' + report.exit_gate.completion_file_reads.control + '→' + report.exit_gate.completion_file_reads.preferred + '.',
    '- Static artifacts: ' + report.exit_gate.static_artifacts_loaded.control + '→' + report.exit_gate.static_artifacts_loaded.preferred + '.',
    '- Artifact-count increase: no.',
    '',
    '## Bundle',
    '',
    '- Route: skill-package-maintenance.',
    '- Graph fragment: ' + report.bundle.graph_nodes + ' nodes / ' + report.bundle.graph_edges + ' edges.',
    '- Provenance entries: ' + report.bundle.provenance_entries + '.',
    '- Space entries: ' + report.bundle.space_entries + '.',
    '- Mutation boundary: ' + report.bundle.mutation_boundary + '.',
    '- Change mode: ' + report.bundle.change_mode + '.',
    '- Reconciliation: ' + report.bundle.reconciliation + '.',
    '- Live state embedded: no.',
    '',
    '## Interpretation',
    '',
    ...report.interpretation.map(item => '- ' + item),
    '',
    'Canonical Skill routing remains authoritative. WP16 updates the skill-formation route while the generated bundle remains only a preferred route context.'
  ].join('\n') + '\n';
}

export async function expectedSkillPackageMaintenanceMigrationOutputs() {
  const report = await buildSkillPackageMaintenanceMigrationReport();
  return new Map([
    ['eval/results/skill-package-maintenance-migration.json', JSON.stringify(report, null, 2) + '\n'],
    ['eval/skill-package-maintenance-migration.md', markdown(report)]
  ]);
}

export async function writeSkillPackageMaintenanceMigrationOutputs({ check = false } = {}) {
  const outputs = await expectedSkillPackageMaintenanceMigrationOutputs();
  const stale = [];
  for (const [relativePath, content] of outputs) {
    const filePath = path.join(root, relativePath);
    if (check) {
      let current = null;
      try { current = await readFile(filePath, 'utf8'); } catch {}
      if (current !== content) stale.push(relativePath);
    } else {
      await mkdir(path.dirname(filePath), { recursive: true });
      await writeFile(filePath, content, 'utf8');
    }
  }
  if (stale.length) throw new Error('Skill-package-maintenance migration report is stale: ' + stale.join(', '));
  return outputs;
}

const entry = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (entry) {
  const outputs = await writeSkillPackageMaintenanceMigrationOutputs({ check: process.argv.includes('--check') });
  const report = JSON.parse(outputs.get('eval/results/skill-package-maintenance-migration.json'));
  console.log('Skill-package-maintenance migrated preferred path: ' + report.preferred_path.utf8_bytes + ' bytes; ' + report.deltas.preferred_vs_current_fallback.percent + '% vs current fallback.');
}
